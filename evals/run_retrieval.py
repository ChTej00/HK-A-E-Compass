"""Does the search find the passage that answers the question?

    python evals/run_retrieval.py                        # keyword search only (instant)
    python evals/run_retrieval.py --embedding bge-m3     # also an embedding model running in Ollama

Each question in `evals/sets/retrieval_questions.jsonl` has a pattern that marks a passage as containing
the answer (for example "$400" for "how much is the A&E fee now?"). A question counts as a hit if one of
the top 3 passages returned contains it. This tests the look-up step on its own, before any AI model
writes an answer. The questions were written by the project author after reading the pages.

Writes evals/reports/retrieval.md (generated; never hand-edited).
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

import pandas as pd

from aecompass.kb.search import EmbeddingSearch, HybridSearch, KeywordSearch, load_chunks
from aecompass.kb.sources import SOURCES

QUESTIONS = Path("evals/sets/retrieval_questions.jsonl")
REPORT = Path("evals/reports/retrieval.md")
K = 5  # passages fetched per question; hits are reported for the top 3 and the top 5


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--embedding", action="append", default=[], help="an Ollama embedding model; repeatable")
    args = parser.parse_args()

    chunks = load_chunks()
    questions = [json.loads(line) for line in QUESTIONS.read_text(encoding="utf-8").splitlines() if line.strip()]
    keyword = KeywordSearch(chunks)
    embedders = [EmbeddingSearch(chunks, model) for model in args.embedding]
    searchers = [keyword, *embedders, *[HybridSearch([keyword, e]) for e in embedders]]

    rows = []
    for q in questions:
        pattern = re.compile(q["answer_pattern"], re.S)
        for s in searchers:
            hits = s.search(q["question"], K)
            rank = next((i + 1 for i, h in enumerate(hits) if pattern.search(h.text)), None)
            rows.append({"method": s.name, "lang": q["lang"], "question": q["question"], "rank": rank,
                         "returned": len(hits)})
    df = pd.DataFrame(rows)
    df["hit"] = df["rank"] <= 3
    df["hit5"] = df["rank"].notna()
    df["top1"] = df["rank"] == 1

    summary = df.groupby(["method", "lang"]).agg(questions=("hit", "size"), hit_in_top_3=("hit", "sum"),
                                                 answer_ranked_first=("top1", "sum"), nothing_returned=("returned", lambda r: (r == 0).sum()))
    total = df.groupby("method").agg(questions=("hit", "size"), hit_in_top_3=("hit", "sum"), hit_in_top_5=("hit5", "sum"), answer_ranked_first=("top1", "sum"))
    out = [
        "# Retrieval evaluation: does the search find the answering passage?",
        "",
        "Generated by `python evals/run_retrieval.py`. Do not edit by hand.",
        "",
        f"Knowledge base: {len(chunks)} passages from {len(SOURCES) - 1} official Hong Kong Government press releases and one fee table "
        "(`src/aecompass/kb/sources.py`). The Hospital Authority's own pages could not be reached from the "
        f"development machine and are not included. {len(questions)} questions "
        f"({sum(q['lang'] == 'zh' for q in questions)} in Chinese/Cantonese), written by the project author. "
        "A hit means one of the top passages contains the answer pattern. The agent's tool returns the top 4.",
        "",
        "| method | questions | answer in top 3 | rate | answer in top 5 | answer ranked first |",
        "|---|---|---|---|---|---|",
        *[f"| {m} | {r.questions} | {r.hit_in_top_3} | {r.hit_in_top_3 / r.questions:.0%} | {r.hit_in_top_5} | {r.answer_ranked_first} |"
          for m, r in total.iterrows()],
        "",
        "By language of the question:",
        "",
        "| method | language | questions | answer in top 3 | rate | nothing returned |",
        "|---|---|---|---|---|---|",
        *[f"| {m} | {lang} | {r.questions} | {r.hit_in_top_3} | {r.hit_in_top_3 / r.questions:.0%} | {r.nothing_returned} |"
          for (m, lang), r in summary.iterrows()],
        "",
    ]
    for s in searchers:
        missed = df[(df["method"] == s.name) & ~df["hit"]]
        out += [f"Questions where {s.name} did not put the answer in the top 3:", "", *([f"- {q}" for q in missed["question"]] or ["- none"]), ""]
    REPORT.write_text("\n".join(out), encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
