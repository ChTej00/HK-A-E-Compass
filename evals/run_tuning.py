"""Does tuning LightGBM's hyperparameters improve the forecast? A time-aware search, then a clean check.

    python evals/run_tuning.py            # about 50 minutes
    python evals/run_tuning.py --quick    # 2 settings, 1 block: a smoke test only, writes nothing to reports

Stage 1, search. `N_CONFIGS` random settings plus the current one are scored on the non-urgent target at
+2h, on blocks `SELECTION_FOLDS` only. Each setting is fitted once with the largest tree count and scored
at several smaller counts by using only its first n trees.

Stage 2, confirm. The winner is compared with the current settings on blocks `CONFIRM_FROM` onward, which
the search never touched, at all three horizons and for both targets.

Rule, fixed before the run: adopt the winner only if, on the confirmation blocks, the non-urgent error is
lower at all three horizons with a mean gain of at least `MIN_GAIN`, and the Triage III error is not
higher on average.

Caveat: the confirmation blocks were scored before for the M2 headline and the feature experiment. They
are untouched by this search, not unseen altogether.

Writes  evals/reports/tuning.md, evals/reports/tuning_search.csv      generated; never hand-edited
        data/eval/tuning_preds.parquet
"""

from __future__ import annotations

import argparse
import json
import time
from pathlib import Path

import lightgbm as lgb
import numpy as np
import pandas as pd

import run_forecast as R
from aecompass.forecast import model as M
from aecompass.forecast.dataset import TARGETS, load_clean, to_panel
from aecompass.forecast.features import build_features, feature_columns
from aecompass.forecast.splits import walk_forward_folds
from aecompass.ref import holidays

SELECTION_FOLDS = (4, 8, 12)
CONFIRM_FROM = 13
TUNE_HORIZON_H = 2
N_CONFIGS = 12
TREE_COUNTS = (200, 400, 800, 1200)
MIN_GAIN = 0.005
SEED = 0
SPACE = {
    "num_leaves": [15, 31, 63, 127, 255],
    "min_child_samples": [50, 200, 500, 1000],
    "learning_rate": [0.03, 0.05, 0.1],
    "colsample_bytree": [0.6, 0.8, 1.0],
    "subsample": [0.6, 0.8, 1.0],
    "reg_lambda": [0.0, 1.0, 10.0],
}
PREDS_PATH = Path("data/eval/tuning_preds.parquet")


def sample_configs(n: int) -> list[dict]:
    """The current settings first, then n random draws from SPACE (same draws every run)."""
    rng = np.random.default_rng(SEED)
    configs = [{k: M.PARAMS[k] for k in SPACE}]
    while len(configs) < n + 1:
        draw = {k: type(v[0])(rng.choice(v)) for k, v in SPACE.items()}
        if draw not in configs:
            configs.append(draw)
    return configs


def search(df, holiday_map, configs, selection_folds, log) -> pd.DataFrame:
    """One row per (setting, tree count, block): MAE in minutes at +2h on the non-urgent target."""
    table = build_features(df, R.MAIN_TARGET, TUNE_HORIZON_H, None, holiday_map)
    feats = feature_columns(table, use_weather=False, use_steps=False, use_neighbours=False)
    folds = walk_forward_folds(to_panel(df, R.MAIN_TARGET).index, R.INITIAL_TRAIN_DAYS, R.TEST_DAYS)
    horizon = pd.Timedelta(hours=TUNE_HORIZON_H)
    rows = []
    for fold in [f for f in folds if f.number in selection_folds]:
        train = table[(table["origin"] + horizon < fold.test_start) & (table["origin"].dt.minute % 30 == 0)]
        test = table[(table["origin"] >= fold.test_start) & (table["origin"] < fold.test_end)]
        for i, config in enumerate(configs):
            t0 = time.time()
            fitted = lgb.LGBMRegressor(**{**M.PARAMS, **config, "n_estimators": max(TREE_COUNTS)})
            fitted.fit(train[feats], train["y"] - train["y_now"])
            for trees in TREE_COUNTS:
                pred = np.clip(test["y_now"].to_numpy() + fitted.predict(test[feats], num_iteration=trees), 0, None)
                rows.append({"config": i, **config, "n_estimators": trees, "fold": fold.number,
                             "mae": float(np.abs(pred - test["y"].to_numpy()).mean())})
            log(f"search block {fold.number:2d} setting {i:2d}: {time.time() - t0:.0f}s {config}")
    return pd.DataFrame(rows)


def write_report(results: pd.DataFrame, best: dict, preds: pd.DataFrame | None, minutes: float) -> str:
    keys = [*SPACE, "n_estimators"]
    ranked = results.groupby(["config", *keys])["mae"].mean().reset_index().sort_values("mae")
    current = ranked[(ranked["config"] == 0) & (ranked["n_estimators"] == M.PARAMS["n_estimators"])]["mae"].iloc[0]
    ranked["vs current"] = (ranked["mae"] / current - 1).map("{:+.2%}".format)
    out = [
        "# Hyperparameter tuning",
        "",
        "Generated by `python evals/run_tuning.py`. Do not edit by hand.",
        "",
        "The values being predicted are the Hospital Authority's **published estimates**, not measured patient "
        "waits. MAE in minutes; lower is better.",
        "",
        f"- Search: {results['config'].nunique() - 1} random settings plus the current one (setting 0), each scored "
        f"at {len(TREE_COUNTS)} tree counts, on the non-urgent target at +{TUNE_HORIZON_H}h, blocks "
        f"{', '.join(map(str, sorted(results['fold'].unique())))} only.",
        f"- Confirmation: blocks {CONFIRM_FROM} onward, never used by the search. They were scored before for the "
        "M2 headline and the feature experiment, so they are untouched by this search, not unseen altogether.",
        f"- Rule fixed before the run: adopt only if the non-urgent error is lower at all three horizons on the "
        f"confirmation blocks with a mean gain of at least {MIN_GAIN:.1%}, and Triage III is not worse on average.",
        f"- Run time: {minutes:.0f} minutes.",
        "",
        "## Search: best 10 of all settings and tree counts (mean MAE over the selection blocks)",
        "",
        R.md(ranked.head(10).set_index("config"), 3),
        "",
        f"Current settings (setting 0 at {M.PARAMS['n_estimators']} trees): {current:.3f}. "
        f"Full table: `tuning_search.csv`.",
        "",
        f"Winner: `{json.dumps(best)}`",
        "",
    ]
    if preds is None:
        out += ["## Verdict", "", "The current settings won the search, so there is nothing to confirm. **KEEP CURRENT**", ""]
        return "\n".join(out)

    gains = {}
    out += [f"## Confirmation on blocks {CONFIRM_FROM} to {preds['fold'].max()}", ""]
    for target, description in TARGETS.items():
        p = preds[preds["target"] == target]
        table = R.mae(p, ["persistence", "model", "model_tuned"], ["horizon_h"])
        gains[target] = table["model_tuned"] / table["model"] - 1
        table["tuned vs current"] = gains[target].map("{:+.2%}".format)
        per_fold = R.mae(p, ["model", "model_tuned"], ["horizon_h", "fold"])
        wins = (per_fold["model_tuned"] < per_fold["model"]).groupby("horizon_h").agg(["sum", "size"])
        table["blocks where tuned wins"] = [f"{a} of {b}" for a, b in wins.to_numpy()]
        out += [f"### `{target}`: {description}", "", R.md(table, 2), ""]
    main, other = gains[R.MAIN_TARGET], gains[[t for t in TARGETS if t != R.MAIN_TARGET][0]]
    checks = {
        "non-urgent better at all three horizons": bool((main < 0).all()),
        f"non-urgent mean gain at least {MIN_GAIN:.1%} (got {-main.mean():.2%})": bool(-main.mean() >= MIN_GAIN),
        f"Triage III not worse on average (got {other.mean():+.2%})": bool(other.mean() <= 0),
    }
    out += ["## Verdict by the rule", ""] + [f"- {name}: {ok}" for name, ok in checks.items()]
    out += ["", f"**{'ADOPT' if all(checks.values()) else 'KEEP CURRENT'}**", ""]
    return "\n".join(out)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--quick", action="store_true")
    args = parser.parse_args()

    started = time.time()
    log = lambda message: print(f"[{(time.time() - started) / 60:5.1f} min] {message}", flush=True)
    df, holiday_map = load_clean(), holidays.load()
    configs = sample_configs(1 if args.quick else N_CONFIGS)
    results = search(df, holiday_map, configs, SELECTION_FOLDS[:1] if args.quick else SELECTION_FOLDS, log)

    mean = results.groupby(["config", "n_estimators"])["mae"].mean()
    config_id, trees = mean.idxmin()
    best = {**configs[config_id], "n_estimators": int(trees)}
    log(f"winner: setting {config_id} with {trees} trees, {mean.min():.3f}")
    is_current = config_id == 0 and trees == M.PARAMS["n_estimators"]

    preds = None
    if not is_current:
        variants = {"model": R.Variant(), "model_tuned": R.Variant(params={**M.PARAMS, **best})}
        first = 24 if args.quick else CONFIRM_FROM
        preds = pd.concat(
            [R.run_target(df, t, variants, None, holiday_map, log, first_fold=first) for t in TARGETS],
            ignore_index=True,
        )
    text = write_report(results, best, preds, (time.time() - started) / 60)
    if not args.quick:
        results.round(4).to_csv(R.REPORTS / "tuning_search.csv", index=False)
        if preds is not None:
            PREDS_PATH.parent.mkdir(parents=True, exist_ok=True)
            preds.to_parquet(PREDS_PATH, index=False)
        (R.REPORTS / "tuning.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
