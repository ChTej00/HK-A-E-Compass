"""Do two new feature groups improve the non-urgent forecast?

    python evals/run_feature_experiment.py        # about 25 minutes

- **steps**: where the series is in its hold-then-jump pattern (how long at this level, last jump, ...).
- **neighbours**: what the three closest other A&Es (straight-line distance) are showing now.

Same walk-forward folds and scored rows as `run_forecast.py`. To keep the check honest, the last
`HELD_BACK` blocks are not looked at when choosing: the decision is made on the earlier ("development")
blocks, and the held-back blocks then confirm or reject it.

Rule, fixed before the run: adopt a variant only if it beats the current model at all three horizons on
the development blocks, and still beats it at all three horizons on the held-back blocks.

Caveat: the held-back blocks were already scored once for the M2 headline numbers, so they are "unseen
by this experiment", not unseen altogether.

Writes  data/eval/feature_experiment_preds.parquet
        evals/reports/feature_experiment.md       generated; never hand-edited
"""

from __future__ import annotations

import time
from pathlib import Path

import pandas as pd

import run_forecast as R
from aecompass.forecast.dataset import load_clean
from aecompass.ref import holidays, hospitals, weather

HELD_BACK = 4
NEIGHBOURS_K = 3
BASE = "model"
CANDIDATES = {
    "model_steps": R.Variant(steps=True),
    "model_neighbours": R.Variant(neighbours=True),
    "model_both": R.Variant(steps=True, neighbours=True),
}
PREDS_PATH = Path("data/eval/feature_experiment_preds.parquet")


def summarise(preds: pd.DataFrame, minutes: float) -> str:
    cols = ["persistence", BASE, *CANDIDATES]
    last_dev = preds["fold"].max() - HELD_BACK
    parts = {"development": preds[preds["fold"] <= last_dev], "held back": preds[preds["fold"] > last_dev]}
    out = [
        "# Feature experiment: step pattern and neighbouring hospitals",
        "",
        "Generated by `python evals/run_feature_experiment.py`. Do not edit by hand.",
        "",
        "Target: Triage IV & V median wait, which is the Hospital Authority's **published estimate**, not a "
        "measured patient wait. MAE in minutes; lower is better. `model` is the current model.",
        "",
        f"- `model_steps` adds 5 features describing the hold-then-jump pattern of the published number.",
        f"- `model_neighbours` adds 5 features from the {NEIGHBOURS_K} closest other A&Es (straight-line distance).",
        "- `model_both` adds both groups.",
        f"- Development blocks 1 to {last_dev} are used to choose. Blocks {last_dev + 1} to {preds['fold'].max()} "
        "were held back and only confirm or reject the choice. They were already scored once for the M2 "
        "headline, so they are unseen by this experiment, not unseen altogether.",
        "- Rule fixed before the run: adopt a variant only if it beats `model` at all three horizons on the "
        "development blocks and again on the held-back blocks.",
        f"- Run time: {minutes:.0f} minutes.",
        "",
    ]
    verdict = {}
    for label, p in parts.items():
        table = R.mae(p, cols, ["horizon_h"])
        change = table[list(CANDIDATES)].div(table[BASE], axis=0) - 1
        verdict[label] = (change < 0).all()
        per_fold = R.mae(p, [BASE, *CANDIDATES], ["horizon_h", "fold"])
        wins = per_fold[list(CANDIDATES)].lt(per_fold[BASE], axis=0).groupby("horizon_h").sum()
        out += [
            f"## {label.capitalize()} blocks ({p['fold'].min()} to {p['fold'].max()}, {len(p):,} forecasts)",
            "",
            R.md(table, 2),
            "",
            "Change against `model`:",
            "",
            R.md(change.map("{:+.2%}".format)),
            "",
            f"Blocks (out of {p['fold'].nunique()}) where the variant beats `model`:",
            "",
            R.md(wins),
            "",
        ]
    out += ["## Verdict by the rule", ""]
    for name in CANDIDATES:
        dev, held = bool(verdict["development"][name]), bool(verdict["held back"][name])
        result = "ADOPT" if dev and held else "REJECT"
        out.append(f"- `{name}`: better at all horizons on development blocks: {dev}; on held-back blocks: {held} -> **{result}**")
    out.append("")
    return "\n".join(out)


def main() -> None:
    started = time.time()
    log = lambda message: print(f"[{(time.time() - started) / 60:5.1f} min] {message}", flush=True)
    df = load_clean()
    neighbours = hospitals.nearest(hospitals.load(), k=NEIGHBOURS_K)
    variants = {BASE: R.VARIANTS[BASE], **CANDIDATES}
    preds = R.run_target(df, R.MAIN_TARGET, variants, weather.load(), holidays.load(), log, neighbours)
    PREDS_PATH.parent.mkdir(parents=True, exist_ok=True)
    preds.to_parquet(PREDS_PATH, index=False)
    text = summarise(preds, (time.time() - started) / 60)
    (R.REPORTS / "feature_experiment.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
