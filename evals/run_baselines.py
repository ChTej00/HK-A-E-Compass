"""Score the three baselines with walk-forward validation.

    python evals/run_baselines.py

Writes  evals/reports/baselines.md               summary tables (generated; never hand-edited)
        evals/reports/baselines_by_hospital.csv
        evals/reports/baselines_by_fold.csv
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from aecompass.forecast.baselines import BASELINES, fold_predictions
from aecompass.forecast.dataset import HORIZONS_H, TARGETS, load_clean, to_panel
from aecompass.forecast.splits import walk_forward_folds

REPORTS = Path("evals/reports")
INITIAL_TRAIN_DAYS = 56
TEST_DAYS = 14


def mae_table(preds: pd.DataFrame, by: list[str]) -> pd.DataFrame:
    """Mean absolute error in minutes for each baseline, grouped by `by`."""
    errors = preds[list(BASELINES)].sub(preds["actual"], axis=0).abs()
    out = errors.join(preds[by]).groupby(by, observed=True).mean()
    out["n"] = preds.groupby(by, observed=True).size()
    return out


def md_table(df: pd.DataFrame, fmt: str = "{:.1f}") -> str:
    df = df.reset_index()
    lines = ["| " + " | ".join(map(str, df.columns)) + " |", "|" + "---|" * len(df.columns)]
    for row in df.itertuples(index=False):
        cells = [fmt.format(v) if isinstance(v, float) else f"{v:,}" if isinstance(v, int) else str(v) for v in row]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def main() -> None:
    df = load_clean()
    REPORTS.mkdir(parents=True, exist_ok=True)
    out = [
        "# Baseline results (walk-forward)",
        "",
        "Generated by `python evals/run_baselines.py`. Do not edit by hand.",
        "",
        "The values being predicted are the Hospital Authority's **published estimates**, not measured",
        "patient waits. All errors are mean absolute error (MAE) in **minutes**; lower is better.",
        "",
    ]
    by_hospital, by_fold = [], []

    for target, description in TARGETS.items():
        panel = to_panel(df, target)
        folds = walk_forward_folds(panel.index, INITIAL_TRAIN_DAYS, TEST_DAYS)
        preds = pd.concat(
            [fold_predictions(panel, fold, h) for fold in folds for h in HORIZONS_H], ignore_index=True
        )
        if target == next(iter(TARGETS)):
            used = sorted(preds["fold"].unique())
            out += [
                f"- Data: {panel.index.min():%d %b %Y} to {panel.index.max():%d %b %Y}, "
                f"{panel.shape[1]} hospitals, 15-minute slots",
                f"- Folds: expanding training window, first test block starts after {INITIAL_TRAIN_DAYS} days, "
                f"each test block is {TEST_DAYS} days. {len(folds)} folds defined, {len(used)} have data.",
                "- A forecast is made at every 15-minute slot for +1h, +2h and +3h.",
                "- Rows are scored only where the actual value and all three baselines exist, so the",
                "  baselines are compared on identical rows.",
                "",
            ]

        overall = mae_table(preds, ["horizon_h"])
        for name in ("seasonal_naive", "historical_mean"):
            overall[f"{name} vs persistence"] = (overall[name] / overall["persistence"] - 1).map("{:+.0%}".format)
        unchanged = (preds["actual"] == preds["persistence"]).groupby(preds["horizon_h"]).mean()
        overall["actual unchanged from now"] = unchanged.map("{:.0%}".format)

        out += [f"## `{target}`: {description}", "", md_table(overall), ""]
        out += [
            f"Mean actual value over the scored rows: {preds['actual'].mean():.0f} minutes. "
            "'vs persistence' is the change in MAE relative to persistence (positive = worse).",
            "",
        ]

        hosp = mae_table(preds, ["hospital", "horizon_h"]).reset_index()
        hosp.insert(0, "target", target)
        by_hospital.append(hosp)
        fold_labels = {f.number: f.label() for f in folds}
        fold_df = mae_table(preds, ["fold", "horizon_h"]).reset_index()
        fold_df.insert(1, "test_period", fold_df["fold"].map(fold_labels))
        fold_df.insert(0, "target", target)
        by_fold.append(fold_df)

        worst = hosp[hosp["horizon_h"] == 3].nlargest(3, "persistence")
        best = hosp[hosp["horizon_h"] == 3].nsmallest(3, "persistence")
        out += [
            "Persistence MAE at +3h by hospital, hardest and easiest:",
            "",
            "- Hardest: " + "; ".join(f"{r.hospital} ({r.persistence:.0f} min)" for r in worst.itertuples()),
            "- Easiest: " + "; ".join(f"{r.hospital} ({r.persistence:.0f} min)" for r in best.itertuples()),
            "",
        ]

    pd.concat(by_hospital).round(2).to_csv(REPORTS / "baselines_by_hospital.csv", index=False)
    pd.concat(by_fold).round(2).to_csv(REPORTS / "baselines_by_fold.csv", index=False)
    out += ["Per-hospital and per-fold numbers: `baselines_by_hospital.csv`, `baselines_by_fold.csv`.", ""]
    (REPORTS / "baselines.md").write_text("\n".join(out), encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
