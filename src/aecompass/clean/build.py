"""Build the clean table from raw snapshots and write a data-quality report.

    python -m aecompass.clean.build

Reads   data/raw/aed/aed_raw_*.jsonl
Writes  data/clean/aed_waits.parquet        one row per hospital per 15-minute slot
        evals/reports/data_quality.md       what was found, generated from the data (never hand-edited)
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import pandas as pd
from pydantic import ValidationError

from .models import clean_snapshot

RAW_ROOT = Path("data/raw/aed")
CLEAN_PATH = Path("data/clean/aed_waits.parquet")
REPORT_PATH = Path("evals/reports/data_quality.md")
WAIT_COLS = ["t3_p50_min", "t3_p95_min", "t45_p50_min", "t45_p95_min"]
STALE_AFTER_MIN = 20  # HA's stamp is normally 15 minutes behind the slot; more means the feed didn't refresh


def load_raw(raw_root: Path) -> tuple[pd.DataFrame, dict]:
    rows, stats = [], {"snapshots": 0, "rejected": 0, "reject_examples": []}
    for path in sorted(raw_root.glob("aed_raw_*.jsonl")):
        with path.open(encoding="utf-8") as f:
            for line in f:
                try:
                    rec = json.loads(line)
                    rows.extend(r.model_dump() for r in clean_snapshot(rec["ts"], rec["body"]))
                    stats["snapshots"] += 1
                except (ValidationError, ValueError, KeyError) as e:
                    stats["rejected"] += 1
                    if len(stats["reject_examples"]) < 5:
                        stats["reject_examples"].append(f"{path.name}: {str(e)[:200]}")
    return pd.DataFrame(rows), stats


def tidy(df: pd.DataFrame) -> tuple[pd.DataFrame, int]:
    """Sort, drop duplicate (hospital, slot) rows, and add the staleness flag."""
    before = len(df)
    df = df.sort_values(["observed_at", "hospital"]).drop_duplicates(["hospital", "observed_at"], keep="last")
    lag_min = (df["observed_at"] - df["update_time"]).dt.total_seconds() / 60
    df = df.assign(stale=lag_min > STALE_AFTER_MIN, hospital=df["hospital"].astype("category"))
    return df.reset_index(drop=True), before - len(df)


def quality_report(df: pd.DataFrame, stats: dict, duplicates: int) -> str:
    first, last = df["observed_at"].min(), df["observed_at"].max()
    expected_slots = int((last - first).total_seconds() // 900) + 1
    slots = df["observed_at"].nunique()
    per_slot = df.groupby("observed_at", observed=True)["hospital"].nunique()

    grid = pd.date_range(first, last, freq="15min")
    missing = grid.difference(pd.DatetimeIndex(df["observed_at"].unique()))
    gaps = []
    if len(missing):
        run_id = (pd.Series(missing).diff() != pd.Timedelta(minutes=15)).cumsum()
        for _, run in pd.Series(missing).groupby(run_id.values):
            gaps.append((run.iloc[0], len(run)))
    gaps.sort(key=lambda g: -g[1])

    lines = [
        "# Data quality report",
        "",
        "Generated by `python -m aecompass.clean.build`. Do not edit by hand.",
        "",
        f"- Period: **{first:%d %b %Y %H:%M}** to **{last:%d %b %Y %H:%M}** HKT",
        f"- Snapshots parsed: **{stats['snapshots']:,}**; rejected by validation: **{stats['rejected']}**",
        f"- Rows (hospital × slot): **{len(df):,}**; duplicate rows removed: **{duplicates}**",
        f"- Hospitals: **{df['hospital'].nunique()}**; slots with a different hospital count: "
        f"**{int((per_slot != df['hospital'].nunique()).sum())}**",
        f"- 15-minute slots present: **{slots:,} of {expected_slots:,}** "
        f"({slots / expected_slots:.2%}); missing: **{len(missing):,}**",
        f"- Stale rows (HA stamp more than {STALE_AFTER_MIN} min behind the slot): "
        f"**{int(df['stale'].sum()):,}** ({df['stale'].mean():.3%})",
        f"- Rows with 'managing multiple resuscitation cases': **{int(df['multi_resus'].sum()):,}** "
        f"({df['multi_resus'].mean():.2%})",
        "",
        "## Unusable values per column",
        "",
        "| Column | Missing or unparseable | Share | Min | Median | Max |",
        "|---|---|---|---|---|---|",
    ]
    for c in WAIT_COLS:
        s = df[c]
        lines.append(
            f"| `{c}` | {int(s.isna().sum()):,} | {s.isna().mean():.3%} | {s.min():.0f} | {s.median():.0f} | {s.max():.0f} |"
        )
    lines += ["", "All waits are in minutes. Triage IV/V values were published in hours and converted.", ""]
    lines += ["## Largest gaps (consecutive missing slots)", ""]
    if gaps:
        lines += ["| Starts (HKT) | Missing slots | Length |", "|---|---|---|"]
        lines += [f"| {start:%d %b %Y %H:%M} | {n} | {n * 15 / 60:.1f} h |" for start, n in gaps[:10]]
        lines.append("")
        lines.append(f"{len(gaps)} gaps in total; {sum(1 for _, n in gaps if n == 1)} are a single missing slot.")
    else:
        lines.append("None.")
    if stats["reject_examples"]:
        lines += ["", "## Rejected snapshots (first few)", ""] + [f"- `{e}`" for e in stats["reject_examples"]]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--raw-root", type=Path, default=RAW_ROOT)
    p.add_argument("--out", type=Path, default=CLEAN_PATH)
    p.add_argument("--report", type=Path, default=REPORT_PATH)
    args = p.parse_args(argv)

    df, stats = load_raw(args.raw_root)
    if df.empty:
        print("no raw data found; run the collector first")
        return 1
    df, duplicates = tidy(df)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    df.to_parquet(args.out, index=False)
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(quality_report(df, stats, duplicates), encoding="utf-8")
    print(f"wrote {len(df):,} rows to {args.out} and the report to {args.report}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
